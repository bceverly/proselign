"""License-header gate: every source file asserts BSD-3-Clause and the
copyright of Bryan C. Everly, from 2026 through the current year.

    check_license_headers.py          report files with a missing or stale header
    check_license_headers.py --fix    add missing headers and bump stale years

The expected copyright line is ``Copyright (c) 2026 Bryan C. Everly`` during
2026 and ``Copyright (c) 2026-YYYY Bryan C. Everly`` afterwards, so on the
first lint of a new year every header is stale until ``make
lint-license-headers-fix`` updates it. Both lines must appear within the
first ten lines, written in the file's own comment syntax.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OWNER = "Bryan C. Everly"
FIRST_YEAR = 2026
SPDX = "SPDX-License-Identifier: BSD-3-Clause"
HEAD_LINES = 10

# Comment syntax by suffix or exact file name: (prefix, suffix).
HASH = ("# ", "")
STYLES: dict[str, tuple[str, str]] = {
    ".py": HASH,
    ".sh": HASH,
    ".yml": HASH,
    ".yaml": HASH,
    ".toml": HASH,
    ".in": HASH,
    ".properties": HASH,
    ".js": ("// ", ""),
    ".css": ("/* ", " */"),
    ".html": ("<!-- ", " -->"),
    ".svg": ("<!-- ", " -->"),
    ".1": ('.\\" ', ""),
}
NAMED: dict[str, tuple[str, str]] = {
    "Makefile": HASH,
    "rules": HASH,
    "control": HASH,
    "proselign.launcher": HASH,
    ".pylintrc": HASH,
    ".pip-audit-ignore": HASH,
}
SKIP_DIRS = {
    ".git",
    ".claude",
    ".venv",
    ".venv-semgrep",
    ".venv-safety",
    "build",
    "dist",
    "htmlcov",
    "__pycache__",
    ".pytest_cache",
    ".scannerwork",
    "docs",
}
# Machine-generated files (regenerated by tools, so never hand-edited).
GENERATED = re.compile(r"^requirements-.*\.txt$")
# Linear-time: the holder is taken to the end of the line, and comment closers
# are trimmed in owner() rather than by a backtracking pattern.
COPYRIGHT_RE = re.compile(r"Copyright \(c\) (\d{4})(?:-(\d{4}))?,? ([^\n]*)", re.MULTILINE)
COMMENT_CLOSERS = ("*/", "-->")


def years(today: dt.date) -> str:
    """``2026`` in the first year, ``2026-YYYY`` afterwards."""
    return str(FIRST_YEAR) if today.year <= FIRST_YEAR else f"{FIRST_YEAR}-{today.year}"


def style_for(path: Path) -> tuple[str, str] | None:
    """Comment syntax for ``path``, or None when it is not a checked source file."""
    if GENERATED.match(path.name) or path.name.endswith(".egg-info"):
        return None
    return NAMED.get(path.name) or STYLES.get(path.suffix)


def source_files(root: Path = ROOT) -> list[Path]:
    """Every checked source file under ``root``."""
    found = []
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root)
        if any(part in SKIP_DIRS or part.endswith(".egg-info") for part in rel.parts[:-1]):
            continue
        if path.is_file() and style_for(path):
            found.append(path)
    return found


def problems(text: str, today: dt.date) -> list[str]:
    """What is wrong with a file's header (empty when it is correct)."""
    head = "\n".join(text.splitlines()[:HEAD_LINES])
    issues = []
    if SPDX not in head:
        issues.append("missing SPDX BSD-3-Clause line")
    match = COPYRIGHT_RE.search(head)
    want = f"Copyright (c) {years(today)} {OWNER}"
    if not match:
        issues.append(f"missing '{want}'")
    elif (
        f"Copyright (c) {match.group(1)}"
        + (f"-{match.group(2)}" if match.group(2) else "")
        + f" {owner(match.group(3))}"
        != want
    ):
        issues.append(f"stale or wrong copyright line; expected '{want}'")
    return issues


def owner(holder: str) -> str:
    """The copyright holder, without trailing whitespace or comment closer."""
    holder = holder.rstrip()
    for closer in COMMENT_CLOSERS:
        holder = holder.removesuffix(closer).rstrip()
    return holder


def inside_root(path: Path, root: Path = ROOT) -> bool:
    """True for a regular file that really lives under ``root`` (no symlinks)."""
    return (
        not path.is_symlink() and path.is_file() and path.resolve().is_relative_to(root.resolve())
    )


def _insert_at(lines: list[str]) -> int:
    """Index after any line that must stay first (shebang, doctype, man title)."""
    if lines and (lines[0].startswith("#!") or lines[0].lower().startswith("<!doctype")):
        return 1
    return 0


def fix(text: str, style: tuple[str, str], today: dt.date) -> str:
    """Return ``text`` with a correct header (idempotent)."""
    prefix, suffix = style
    want = f"Copyright (c) {years(today)} {OWNER}"
    lines = text.splitlines(keepends=True)
    head = lines[:HEAD_LINES]

    for i, line in enumerate(head):
        if COPYRIGHT_RE.search(line):
            lines[i] = f"{prefix}{want}{suffix}\n"
            break
    else:
        spdx_at = next((i for i, line in enumerate(head) if SPDX in line), None)
        if spdx_at is not None:
            lines.insert(spdx_at + 1, f"{prefix}{want}{suffix}\n")
        else:
            at = _insert_at(lines)
            block = [f"{prefix}{SPDX}{suffix}\n", f"{prefix}{want}{suffix}\n"]
            lines[at:at] = block
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Check (or with --fix, repair) every source file's header."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fix", action="store_true")
    args = parser.parse_args(argv)
    today = dt.date.today()

    bad = []
    for path in source_files():
        if not inside_root(path):  # never read or rewrite anything outside the repo
            continue
        text = path.read_text("utf-8")
        issues = problems(text, today)
        if not issues:
            continue
        if args.fix:
            path.write_text(fix(text, style_for(path), today), "utf-8")
            print(f"fixed {path.relative_to(ROOT)}")
        else:
            bad.append((path, issues))

    if bad:
        print("ERROR: source files with a missing or stale license header:", file=sys.stderr)
        for path, issues in bad:
            print(f"  {path.relative_to(ROOT)}: {'; '.join(issues)}", file=sys.stderr)
        print("Run: make lint-license-headers-fix", file=sys.stderr)
        return 1
    print(f"[OK] license headers present ({years(today)} {OWNER})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
